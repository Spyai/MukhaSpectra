"""Write the SYNTHETIC demo patients to disk as an upload-ready sample set.

Layout (one folder per patient, ``low`` | ``moderate`` | ``high``)::

    SYNTHETIC_<site>_wl.jpg     white-light capture (JPEG q=92, EXIF marks it SYNTHETIC)
    SYNTHETIC_<site>_af.jpg     405 nm autofluorescence capture
    SYNTHETIC_<site>_dark.png   dark frame (LEDs off, AF exposure)
    spectrum.csv                Confirm-probe readings, spectral CSV v1 (+ white reference rows
                                when the case is calibrated)
    manifest.json               upload manifest (docs/architecture.md §6); every file field name
                                is the file name without its extension

Regenerate with ``python -m mukha_pipeline.synthetic [out_dir]``. The set is deterministic for a
seed, so a regenerated folder is byte-identical unless the generator changed.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
from PIL import Image, PngImagePlugin, TiffImagePlugin

from mukha_pipeline.schema.models import CaptureMetadata, DataProvenance
from mukha_pipeline.synthetic.patients import (
    DEMO_KINDS,
    DemoBundle,
    make_demo_bundle,
)
from mukha_pipeline.synthetic.spectra import spectral_inputs_to_csv
from mukha_pipeline.synthetic.wl import DEFAULT_SIZE

JPEG_QUALITY = 92
SPECTRUM_FILE = "spectrum.csv"
MANIFEST_FILE = "manifest.json"
EXIF_DESCRIPTION = "SYNTHETIC image generated by mukha_pipeline.synthetic - not a real patient"

# EXIF tag ids (TIFF/EXIF 2.3).
_IMAGE_DESCRIPTION, _MAKE, _MODEL, _SOFTWARE, _DATETIME = 0x010E, 0x010F, 0x0110, 0x0131, 0x0132
_EXIF_IFD = 0x8769
_EXPOSURE_TIME, _ISO, _DATETIME_ORIGINAL, _WHITE_BALANCE = 0x829A, 0x8827, 0x9003, 0xA403


def default_out_dir() -> Path:
    """<repo>/sample_data/synthetic when run from a source checkout, else ./sample_data/..."""
    repo = Path(__file__).resolve().parents[3]
    if (repo / "sample_data").is_dir():
        return repo / "sample_data" / "synthetic"
    return Path.cwd() / "sample_data" / "synthetic"


def _to_uint8(img: np.ndarray) -> np.ndarray:
    return np.round(np.clip(img, 0.0, 1.0) * 255.0).astype(np.uint8)


def _exif(meta: CaptureMetadata) -> Image.Exif:
    """EXIF that labels the file SYNTHETIC and carries the (locked) capture settings."""
    exif = Image.Exif()
    exif[_IMAGE_DESCRIPTION] = EXIF_DESCRIPTION
    exif[_MAKE] = "MukhaSpectra SYNTHETIC"
    exif[_MODEL] = meta.device_id or "SYNTHETIC"
    exif[_SOFTWARE] = "mukha_pipeline.synthetic"
    stamp = meta.captured_at.strftime("%Y:%m:%d %H:%M:%S") if meta.captured_at else None
    if stamp:
        exif[_DATETIME] = stamp
    ifd = exif.get_ifd(_EXIF_IFD)
    if meta.exposure_time_ms:
        ifd[_EXPOSURE_TIME] = TiffImagePlugin.IFDRational(int(round(meta.exposure_time_ms)), 1000)
    if meta.iso:
        ifd[_ISO] = int(meta.iso)
    if stamp:
        ifd[_DATETIME_ORIGINAL] = stamp
    ifd[_WHITE_BALANCE] = 1  # manual (locked)
    return exif


def _write_jpeg(path: Path, img: np.ndarray, meta: CaptureMetadata) -> None:
    Image.fromarray(_to_uint8(img), "RGB").save(
        path, "JPEG", quality=JPEG_QUALITY, optimize=True, exif=_exif(meta)
    )


def _write_png(path: Path, img: np.ndarray, meta: CaptureMetadata) -> None:
    info = PngImagePlugin.PngInfo()
    info.add_text("Description", EXIF_DESCRIPTION)
    info.add_text("Software", "mukha_pipeline.synthetic")
    Image.fromarray(_to_uint8(img), "RGB").save(
        path, "PNG", optimize=True, pnginfo=info, exif=_exif(meta)
    )


def _stem(name: str | None) -> str:
    if not name:
        raise ValueError("capture metadata has no file name")
    return Path(name).stem


def build_manifest(bundle: DemoBundle) -> dict[str, Any]:
    """Upload manifest (docs/architecture.md §6) for a demo patient."""
    scr = bundle.screening
    sites: list[dict[str, Any]] = []
    for s in scr.sites:
        entry: dict[str, Any] = {
            "site": s.site.value,
            "role": s.role.value,
            "wl": _stem(s.wl.meta.file_name),
            "af": _stem(s.af.meta.file_name),
        }
        if s.dark is not None:
            entry["dark"] = _stem(s.dark.meta.file_name)
        entry.update(
            {
                "visual_flag": s.visual_flag.model_dump(mode="json"),
                "diascopy": s.diascopy.value,
                "px_per_mm": s.px_per_mm,
                "device_id": s.wl.meta.device_id,
                "firmware_version": s.wl.meta.firmware_version,
            }
        )
        sites.append(entry)
    manifest: dict[str, Any] = {
        "patient": {
            "name": bundle.spec.display_name,
            "external_id": scr.patient.pseudonymous_id,
            "age_years": scr.patient.age_years,
            "sex": scr.patient.sex.value,
        },
        "consent": {
            "consent_recorded": scr.consent.consent_recorded,
            "method": scr.consent.method,
            "language": scr.consent.language.value,
            "research_use_opt_in": scr.consent.research_use_opt_in,
        },
        "risk_factors": scr.risk_factors.model_dump(mode="json"),
        "context": {
            "screening_site_name": scr.context.screening_site_name,
            "health_worker_id": scr.context.health_worker_id,
        },
        "data_provenance": DataProvenance.SYNTHETIC.value,
        "sites": sites,
    }
    if scr.spectral:
        manifest["spectral_file"] = Path(SPECTRUM_FILE).stem
    return manifest


def write_patient(bundle: DemoBundle, folder: Path) -> list[Path]:
    """Write one demo patient's images, spectrum and manifest; returns the written paths."""
    folder.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for s in bundle.screening.sites:
        for cap, writer in ((s.wl, _write_jpeg), (s.af, _write_jpeg), (s.dark, _write_png)):
            if cap is None:
                continue
            path = folder / str(cap.meta.file_name)
            writer(path, cap.image, cap.meta)
            written.append(path)
    if bundle.screening.spectral:
        path = folder / SPECTRUM_FILE
        path.write_text(
            spectral_inputs_to_csv(bundle.screening.spectral, bundle.white_reference),
            encoding="utf-8",
        )
        written.append(path)
    path = folder / MANIFEST_FILE
    path.write_text(json.dumps(build_manifest(bundle), indent=2) + "\n", encoding="utf-8")
    written.append(path)
    return written


def write_sample_data(
    out_dir: Path | str,
    *,
    seed: int = 0,
    size: tuple[int, int] = DEFAULT_SIZE,
    kinds: tuple[str, ...] = DEMO_KINDS,
    now: datetime | None = None,
) -> list[Path]:
    """Write the SYNTHETIC demo patients under ``out_dir/<kind>/``; returns the written paths."""
    out = Path(out_dir)
    written: list[Path] = []
    for kind in kinds:
        bundle = make_demo_bundle(kind, seed, now=now, size=size)
        written.extend(write_patient(bundle, out / kind))
    return written


def _parse_size(text: str) -> tuple[int, int]:
    h, _, w = text.lower().partition("x")
    return int(h), int(w)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m mukha_pipeline.synthetic",
        description="Write the SYNTHETIC demo patients (low, moderate, high) to a folder.",
    )
    parser.add_argument("out_dir", nargs="?", type=Path, default=None)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--size", type=_parse_size, default=DEFAULT_SIZE, help="HxW, e.g. 768x1024")
    args = parser.parse_args(argv)
    out_dir = args.out_dir or default_out_dir()
    written = write_sample_data(out_dir, seed=args.seed, size=args.size)
    total = sum(p.stat().st_size for p in written)
    print(f"Wrote {len(written)} SYNTHETIC files ({total / 1e6:.2f} MB) to {out_dir}")
    return 0
